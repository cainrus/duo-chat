/// <reference types="vitest/config" />
import { fileURLToPath, URL } from 'node:url'
import { defineConfig, type Plugin } from 'vite'
import vue from '@vitejs/plugin-vue'
import Components from 'unplugin-vue-components/vite'
import { VantResolver } from '@vant/auto-import-resolver'
import Icons from 'unplugin-icons/vite'

const alias = {
  '@shared': fileURLToPath(new URL('./src/shared', import.meta.url)),
  '@client': fileURLToPath(new URL('./src/client', import.meta.url)),
  '@server': fileURLToPath(new URL('./src/server', import.meta.url)),
}

/**
 * Vant's icon font CSS carries a remote fallback `url(//at.alicdn.com/...woff)` after the
 * inlined woff2 data URI. The CSP blocks it anyway, but no third-party host may appear in
 * dist/, so it is cut out at build time.
 */
function stripRemoteFontFallback(): Plugin {
  return {
    name: 'duo:strip-remote-font-fallback',
    enforce: 'pre',
    transform(code, id) {
      if (!id.includes('vant') || !id.endsWith('.css') || !code.includes('alicdn')) return null
      return { code: code.replace(/,\s*url\(\/\/at\.alicdn\.com[^)]*\)\s*format\("woff"\)/g, ''), map: null }
    },
  }
}

const testing = !!process.env.VITEST

export default defineConfig({
  plugins: [
    vue(),
    stripRemoteFontFallback(),
    Components({
      // Typed global components for vue-tsc; regenerated by dev/build, committed.
      dts: 'src/client/ui/components.d.ts',
      dirs: [],
      // Vitest runs in Node and cannot load the CSS side-imports.
      resolvers: [VantResolver({ importStyle: !testing })],
    }),
    Icons({ compiler: 'vue3' }),
  ],
  resolve: { alias },
  build: {
    // Reproducible output: no sourcemaps with absolute paths, stable hashes.
    sourcemap: false,
  },
  test: {
    include: ['src/**/*.test.ts', 'build/**/*.test.ts', 'scripts/**/*.test.ts'],
    environment: 'node',
    server: { deps: { inline: ['vant'] } },
  },
})
